// Generates a local .env with FRESH random keys for docker compose. Refuses to overwrite. Run: pnpm env:init
import { existsSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { generateKeypair, publicKeyOf } from "../packages/log-core/src/index.js";

const path = new URL("../.env", import.meta.url);
if (existsSync(path)) { console.error(".env already exists: not overwriting (delete it to regenerate)"); process.exit(1); }
const log = generateKeypair(), vendor = generateKeypair(), ws = [1, 2, 3].map(() => generateKeypair());
writeFileSync(path, [
  "# Generated by pnpm env:init. Demo keys, gitignored. Never commit.",
  `LOG_SECRET_KEY=${log.secretKey}`,
  "VENDOR_KEY_ID=demo",
  `VENDOR_SECRET_KEY=${vendor.secretKey}`,
  `VENDOR_PUBLIC_KEYS='${JSON.stringify({ demo: vendor.publicKey })}'`,
  `LOG_PUBLIC_KEY=${publicKeyOf(log.secretKey)}`,
  ...ws.map((k, i) => `WITNESS_${i + 1}_SECRET_KEY=${k.secretKey}`),
  `WITNESS_PUBLIC_KEYS='${JSON.stringify(Object.fromEntries(ws.map((k, i) => [`w${i + 1}`, k.publicKey])))}'`,
  `MONITOR_TOKEN=${randomBytes(24).toString("hex")}`,
  `ADMIN_TOKEN=${randomBytes(24).toString("hex")}`, // demo-only reset of witnesses and monitor "",
].join("\n"), { mode: 0o600 });
console.log("wrote .env (log, vendor, 3 witness keys, monitor token)");
