// Deterministic test vectors: fixed-seed keys, fixed timestamps, 16 leaves. Run: pnpm fixtures
// Keys here are PUBLIC TEST KEYS. Never reuse outside tests.
import { writeFileSync } from "node:fs";
import { sha256 } from "@noble/hashes/sha2.js";
import { bytesToHex } from "@noble/hashes/utils.js";
import { consistencyPath, cosign, inclusionPath, leafHashOfEntry, publicKeyOf, rootHash, signEntry, signSTH } from "../packages/log-core/src/index.js";

const secret = (name: string) => btoa(String.fromCharCode(...sha256(new TextEncoder().encode(`uw-fixture-key/${name}`))));
const keys = Object.fromEntries(["vendor", "log", "w1", "w2", "w3"].map((n) => [n, { secretKey: secret(n), publicKey: publicKeyOf(secret(n)) }]));
const flipB64 = (s: string) => (s[0] === "A" ? "B" : "A") + s.slice(1);
const flipHex = (h: string) => (h[0] === "0" ? "1" : "0") + h.slice(1);
const T = "2026-01-01T00:00:00.000Z", TC = "2026-01-01T00:01:00.000Z";

export function build() {
  const entries = Array.from({ length: 16 }, (_, i) => signEntry({
    app: "notepad-minus", version: `2.0.${i}`, platform: (["win-x64", "mac-arm64", "linux-x64"] as const)[i % 3],
    sha256: bytesToHex(sha256(new TextEncoder().encode(`binary-${i}`))), size: 1000 + i, url: `https://example.test/${i}`,
    publishedAt: T, vendorKeyId: "vendor",
  }, keys.vendor.secretKey));
  const leaves = entries.map(leafHashOfEntry);
  const body = { logId: "fixture-log", treeSize: 16, rootHash: rootHash(leaves), timestamp: T };
  const sth = { ...signSTH(body, keys.log.secretKey), cosigs: ["w1", "w2", "w3"].map((w) => cosign(body, w, keys[w as "w1"].secretKey, TC)) };
  const inclusion = leaves.map((_, i) => ({ leafIndex: i, treeSize: 16, path: inclusionPath(leaves, i) }));
  const consistency = [1, 5, 8, 13, 16].map((m) => ({ fromSize: m, toSize: 16, fromRoot: rootHash(leaves.slice(0, m)), path: consistencyPath(leaves, m) }));
  const e5 = entries[5], p5 = inclusion[5];
  const tampered = {
    entryHashChanged: { ...e5, sha256: flipHex(e5.sha256) },       // must fail vendor sig and inclusion
    entryBadVendorSig: { ...e5, vendorSig: flipB64(e5.vendorSig) },
    inclusionPathFlipped: { ...p5, path: [flipHex(p5.path[0]), ...p5.path.slice(1)] },
    inclusionWrongIndex: { ...p5, leafIndex: 6 },
    sthRootChanged: { ...sth, rootHash: flipHex(sth.rootHash) },
    sthBadLogSig: { ...sth, logSig: flipB64(sth.logSig) },
    sthOneCosigBad: { ...sth, cosigs: [{ ...sth.cosigs[0], sig: flipB64(sth.cosigs[0].sig) }, ...sth.cosigs.slice(1)] },
    sthOneCosigOnly: { ...sth, cosigs: sth.cosigs.slice(0, 1) },
    sthCosigWrongWitness: { ...sth, cosigs: sth.cosigs.map((c, i) => (i === 0 ? { ...c, witnessId: "w2" } : c)) },
    consistencyPathFlipped: { ...consistency[1], path: [flipHex(consistency[1].path[0]), ...consistency[1].path.slice(1)] },
  };
  return { note: "Generated by fixtures/generate.ts. Do not edit by hand.", keys, entries, leaves, sth, inclusion, consistency, tampered };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("./vectors.json", import.meta.url), JSON.stringify(build(), null, 2) + "\n");
  console.log("wrote fixtures/vectors.json");
}
